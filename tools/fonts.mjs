// Build a lean fonts.css: only the @font-face rules the site actually needs.
// The fontsource packages ship one rule per unicode subset (Zen Kaku Gothic has ~120 Japanese
// subsets per weight, about 250 KB of CSS). We keep the Latin rule plus the subsets that contain the
// non-Latin characters used in the source and content, and copy just those font files to public/.
//   node tools/fonts.mjs   -> src/styles/fonts.css, public/fonts/*.woff2
import { copyFileSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const FAMILIES = [
  { pkg: '@fontsource/zen-kaku-gothic-new', weights: [400, 700, 900] },
  // the LED face: DotGothic16 only for kana and kanji (its Latin letters are unevenly spaced),
  // VT323 for the Latin letters and digits
  { pkg: '@fontsource/dotgothic16', weights: [400], latin: false },
  { pkg: '@fontsource/vt323', weights: [400] },
];

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(astro|ts|md|json|ya?ml)$/.test(f) ? [p] : [];
  });

// every codepoint above Latin-1 that the site can render
const used = new Set();
for (const file of walk('src')) for (const ch of readFileSync(file, 'utf8')) if (ch.codePointAt(0) > 0xff) used.add(ch.codePointAt(0));

const inRange = (cp, range) =>
  range.split(',').some((part) => {
    const r = part.trim().replace(/^U\+/i, '');
    if (r.includes('?')) return cp >= parseInt(r.replace(/\?/g, '0'), 16) && cp <= parseInt(r.replace(/\?/g, 'f'), 16);
    const [a, b] = r.split('-').map((h) => parseInt(h, 16));
    return cp >= a && cp <= (b ?? a);
  });

mkdirSync('public/fonts', { recursive: true });
let css = '/* generated by tools/fonts.mjs: Latin plus only the subsets the site uses */\n';
const missing = new Set(used);
for (const { pkg, weights, latin = true } of FAMILIES) {
  for (const w of weights) {
    const src = readFileSync(`node_modules/${pkg}/${w}.css`, 'utf8');
    for (const rule of src.match(/@font-face\s*{[^}]+}/g)) {
      const range = /unicode-range:\s*([^;]+);/.exec(rule)?.[1] ?? '';
      const isLatin = /U\+0000-00FF/i.test(range);
      const hits = [...used].filter((cp) => inRange(cp, range));
      if (isLatin ? !latin : hits.length === 0) continue;
      hits.forEach((cp) => missing.delete(cp));
      const out = rule.replace(/url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\)(,\s*url\([^)]+\)\s*format\('woff'\))?/g, (_, file) => {
        copyFileSync(`node_modules/${pkg}/files/${file}`, `public/fonts/${file}`);
        return `url(/fonts/${file}) format('woff2')`;
      });
      css += out.replace(/\n\s*/g, '\n  ').replace(/\n {2}}$/, '\n}') + '\n';
    }
  }
}
writeFileSync('src/styles/fonts.css', css);
console.log(`fonts.css ${css.length} bytes; glyphs without a font subset (fall back to system):`, [...missing].map((c) => String.fromCodePoint(c)).join(' ') || 'none');
